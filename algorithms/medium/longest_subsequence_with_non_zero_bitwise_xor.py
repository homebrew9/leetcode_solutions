from typing import List

class Solution:
    def longestSubsequence(self, nums: List[int]) -> int:
        num_set = set(nums)
        if len(num_set) == 1 and list(num_set)[0] == 0:
            return 0
        N = len(nums)
        res = 0
        for i in range(N):
            res ^= nums[i]
        return N if res > 0 else N - 1

